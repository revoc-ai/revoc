from __future__ import annotations

import asyncio
import json
import tempfile
from pathlib import Path
from typing import Any

import jsonschema
import yaml

_SCHEMA_PATH = (
    Path(__file__).parent.parent.parent.parent
    / "policies"
    / "schemas"
    / "policy_manifest.json"
)


class PolicyCompilerService:
    """Compile a PolicyManifest YAML into a validated Rego bundle."""

    async def compile(self, yaml_content: str) -> tuple[str, list[str]]:
        """Parse YAML, validate schema, generate Rego, opa-check it.

        Returns (rego_str, errors). On any error rego_str is empty.
        """
        # 1 — Parse YAML
        try:
            policy: dict[str, Any] = yaml.safe_load(yaml_content)
        except yaml.YAMLError as exc:
            return "", [f"YAML parse error: {exc}"]

        if not isinstance(policy, dict):
            return "", ["YAML must be a mapping at the top level"]

        # Unwrap single top-level wrapper key (OPA example files use one)
        policy = self._unwrap_manifest(policy)

        # 2 — Validate against JSON schema
        if _SCHEMA_PATH.exists():
            schema: dict[str, Any] = json.loads(_SCHEMA_PATH.read_text(encoding="utf-8"))
            try:
                jsonschema.validate(policy, schema)
            except jsonschema.ValidationError as exc:
                return "", [f"Schema validation: {exc.message}"]

        # 3 — Generate Rego
        rego = self._generate_rego(policy)

        # 4 — opa check
        opa_errors = await self._opa_check(rego)
        if opa_errors:
            return "", opa_errors

        return rego, []

    # ── helpers ──────────────────────────────────────────────────────────────

    def _unwrap_manifest(self, policy: dict[str, Any]) -> dict[str, Any]:
        """Unwrap a single top-level wrapper key if present."""
        if len(policy) == 1:
            inner = next(iter(policy.values()))
            if isinstance(inner, dict) and "apiVersion" in inner:
                return inner
        return policy

    def _generate_rego(self, policy: dict[str, Any]) -> str:
        spec: dict[str, Any] = policy.get("spec", {})
        profile: str | None = spec.get("profile")
        model_restrictions: dict[str, Any] = spec.get("model_restrictions", {})
        quotas: dict[str, Any] = spec.get("quotas", {})

        lines: list[str] = [
            "package revoc.governance.custom",
            "",
            "import future.keywords.if",
            "import future.keywords.in",
            "import future.keywords.contains",
            "",
            "# Generated by REVOC PolicyCompilerService — do not edit manually.",
            "",
        ]

        # Delegate to compliance profile
        if profile:
            pkg = profile.replace("-", "_")
            lines += [
                "violations contains v if {",
                f'    input.caller.policy_profile == "{profile}"',
                f"    v := data.revoc.governance.profile.{pkg}.violations[_]",
                "}",
                "",
            ]

        # Custom model ACL
        allowed_models: list[str] = model_restrictions.get("allowed_models", [])
        if allowed_models:
            models_json = json.dumps(allowed_models)
            lines += [
                "violations contains v if {",
                "    is_string(input.model)",
                f"    allowed := {models_json}",
                "    not input.model in allowed",
                "    v := {",
                '        "rule_id": "custom_model_acl_v1",',
                '        "message": "Model not permitted by policy",',
                '        "severity": "MEDIUM",',
                '        "action": "block",',
                '        "tier": "custom",',
                "    }",
                "}",
                "",
            ]

        # Custom token quota
        default_quota: dict[str, Any] = quotas.get("default", {})
        limit: int | None = default_quota.get("tokens_per_request")
        if limit is not None:
            lines += [
                "violations contains v if {",
                "    input.token_usage != null",
                f"    input.token_usage.total_tokens > {limit}",
                "    v := {",
                '        "rule_id": "custom_quota_v1",',
                '        "message": "Token quota exceeded",',
                '        "severity": "HIGH",',
                '        "action": "block",',
                '        "tier": "custom",',
                "    }",
                "}",
                "",
            ]

        return "\n".join(lines)

    async def _opa_check(self, rego: str) -> list[str]:
        """Run `opa check` on the generated Rego. Returns a list of error strings."""
        with tempfile.NamedTemporaryFile(
            suffix=".rego", mode="w", delete=False, encoding="utf-8"
        ) as tmp:
            tmp.write(rego)
            fname = tmp.name

        try:
            try:
                proc = await asyncio.create_subprocess_exec(
                    "opa", "check", fname,
                    stdout=asyncio.subprocess.PIPE,
                    stderr=asyncio.subprocess.PIPE,
                )
            except FileNotFoundError:
                # OPA not on PATH — skip static check in this environment
                return []

            try:
                _, stderr = await asyncio.wait_for(proc.communicate(), timeout=10.0)
            except TimeoutError:
                proc.kill()
                return ["opa check timed out after 10 seconds"]

            if proc.returncode != 0:
                return [stderr.decode(errors="replace").strip()]
            return []
        finally:
            Path(fname).unlink(missing_ok=True)
