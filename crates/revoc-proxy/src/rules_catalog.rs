//! Generated reference of the built-in detection patterns and the policy
//! decision each one produces (`revoc-proxy list-rules`).
//!
//! Nothing here is hand-maintained: patterns come from the detector's
//! compiled tables, and each rule ID and action is obtained by running a
//! finding shaped exactly like the detector's through the native policy
//! engine. The committed page `docs/docs/default-rules/catalog.md` is
//! checked against this output by a test, so it cannot drift from the code.

use std::fmt::Write as _;

use revoc_core::{
    Action, CallerContext, DetectionTier, EnforcementMode, Finding, FindingType, PiiEntityType,
    PolicyInput, RequestType, SessionState, Severity,
};
use revoc_detector::patterns::{financial, pii, secrets, security};
use revoc_policy::native::NativePolicyEngine;

/// One row of the catalog.
struct Row {
    name: &'static str,
    detects: String,
    severity: Severity,
    confidence: f64,
    validator: bool,
    regex: String,
    finding: Finding,
}

fn action(a: &Action) -> &'static str {
    match a {
        Action::Allow => "allow",
        Action::Block => "block",
        Action::Redact => "redact",
        Action::Audit => "audit",
    }
}

fn input(findings: Vec<Finding>, request_type: RequestType) -> PolicyInput {
    PolicyInput {
        request_id: "catalog".into(),
        request_type,
        caller: CallerContext::default(),
        findings,
        model: None,
        provider: None,
        messages: None,
        tool_call: None,
        tool_result: None,
        token_usage: None,
        session_state: None,
        governance_depth: 0,
        timestamp: 0,
    }
}

/// `action (rule, rule)` for `findings` evaluated as `request_type`.
fn decide(findings: Vec<Finding>, request_type: RequestType) -> String {
    let engine = NativePolicyEngine::new(EnforcementMode::Enforce);
    let d = engine.evaluate_sync(&input(findings, request_type));
    let mut rules = d.applicable_rules.clone();
    rules.sort();
    rules.dedup();
    if rules.is_empty() {
        action(&d.action).to_owned()
    } else {
        let ids: Vec<String> = rules.iter().map(|r| format!("`{r}`")).collect();
        format!("{} ({})", action(&d.action), ids.join(", "))
    }
}

fn entity_finding(t: FindingType, severity: &Severity, entity: &PiiEntityType) -> Finding {
    Finding::new(t, severity.clone(), DetectionTier::Regex).with_pii(entity.clone())
}

fn rows() -> Vec<(&'static str, Vec<Row>)> {
    let pii_rows = |patterns: &'static [pii::PiiPattern]| -> Vec<Row> {
        patterns
            .iter()
            .map(|p| Row {
                name: p.name,
                detects: p.entity_type.to_string(),
                severity: p.severity.clone(),
                confidence: p.confidence,
                validator: p.validator.is_some(),
                regex: p.regex.as_str().to_owned(),
                finding: entity_finding(FindingType::Pii, &p.severity, &p.entity_type),
            })
            .collect()
    };
    let secret_rows = secrets::all_secret_patterns()
        .iter()
        .map(|p| Row {
            name: p.name,
            detects: p.entity_type.to_string(),
            severity: p.severity.clone(),
            confidence: p.confidence,
            validator: false,
            regex: p.regex.as_str().to_owned(),
            finding: entity_finding(FindingType::SecretExposure, &p.severity, &p.entity_type),
        })
        .collect();
    let security_rows = security::all_security_patterns()
        .iter()
        .map(|p| {
            let mut f = Finding::new(
                p.finding_type.clone(),
                p.severity.clone(),
                DetectionTier::Regex,
            );
            f.metadata.insert(
                "pattern_name".into(),
                serde_json::Value::String(p.name.to_owned()),
            );
            Row {
                name: p.name,
                detects: format!("{:?}", p.finding_type),
                severity: p.severity.clone(),
                confidence: p.confidence,
                validator: p.skip_if_after_contains.is_some(),
                regex: p.regex.as_str().to_owned(),
                finding: f,
            }
        })
        .collect();
    vec![
        ("PII", pii_rows(pii::all_pii_patterns())),
        ("Financial", pii_rows(financial::all_financial_patterns())),
        ("Secrets", secret_rows),
        ("Security", security_rows),
    ]
}

/// The catalog as Markdown.
pub fn markdown() -> String {
    let mut md = String::new();
    let groups = rows();
    let total: usize = groups.iter().map(|(_, r)| r.len()).sum();
    let _ = writeln!(
        md,
        "# Rule Catalog (generated)\n\n\
         <!-- Generated by `revoc-proxy list-rules`. Do not edit: a test fails if this \
         page differs from the code. Regenerate with\n     \
         cargo run -p revoc-proxy -- list-rules > docs/docs/default-rules/catalog.md -->\n\n\
         Every built-in regex pattern ({total}) and the decision the native policy engine \
         makes when it matches, in enforce mode. Each decision is computed by running a \
         finding shaped like the detector's through the engine; nothing on this page is \
         written by hand.\n\n\
         - **Request / MCP call** — the match is in an LLM request or in MCP tool arguments.\n\
         - **LLM response** — the match is in the model's response.\n\
         - **MCP tool result** — the match is in a tool result returned to the agent.\n\
         - **Check** — a validator that must also pass (Luhn, IBAN checksum, …), or for \
         security patterns a keyword whose presence right after the match suppresses it.\n\n\
         Patterns run after normalization (NFKC, zero-width / BIDI / control characters \
         removed) and also on decoded base64 / URL-encoded content."
    );
    for (group, rows) in &groups {
        let _ = writeln!(
            md,
            "\n## {group} ({})\n\n\
             | Pattern | Detects | Severity | Confidence | Check | Request / MCP call | LLM response | MCP tool result |\n\
             |---|---|---|---:|:---:|---|---|---|",
            rows.len()
        );
        for r in rows {
            let _ = writeln!(
                md,
                "| `{}` | {} | {:?} | {:.2} | {} | {} | {} | {} |",
                r.name,
                r.detects,
                r.severity,
                r.confidence,
                if r.validator { "yes" } else { "—" },
                decide(vec![r.finding.clone()], RequestType::LlmRequest),
                decide(vec![r.finding.clone()], RequestType::LlmResponse),
                decide(vec![r.finding.clone()], RequestType::McpToolResult),
            );
        }
    }

    // Context rules: not tied to one pattern.
    let sample = entity_finding(
        FindingType::Pii,
        &Severity::Medium,
        &PiiEntityType::EmailAddress,
    );
    let mut encoded = sample.clone();
    encoded.was_encoded = true;
    let mut session_input = input(vec![], RequestType::McpToolCall);
    session_input.session_state = Some(SessionState {
        session_id: "catalog".into(),
        org_id: "catalog".into(),
        caller_id: "catalog".into(),
        tools_called: Vec::new(),
        total_rows_read: 501,
        pii_entities_seen: std::iter::once("EMAIL_ADDRESS".to_owned()).collect(),
        external_send_attempted: true,
        started_at: chrono::DateTime::UNIX_EPOCH,
        last_active: chrono::DateTime::UNIX_EPOCH,
    });
    let session = NativePolicyEngine::new(EnforcementMode::Enforce).evaluate_sync(&session_input);
    let mut session_rules = session.applicable_rules.clone();
    session_rules.sort();
    let _ = writeln!(
        md,
        "\n## Context rules\n\n\
         | Condition | Decision |\n|---|---|\n\
         | Any match found inside encoded (base64 / URL-encoded) content | {} |\n\
         | Session has read > 500 rows, seen PII, and attempts an external send | {} ({}) |",
        decide(vec![encoded], RequestType::LlmRequest),
        action(&session.action),
        session_rules
            .iter()
            .map(|r| format!("`{r}`"))
            .collect::<Vec<_>>()
            .join(", "),
    );

    let _ = writeln!(md, "\n## Patterns\n");
    for (_, rows) in &groups {
        for r in rows {
            let _ = writeln!(md, "### `{}`\n\n```text\n{}\n```\n", r.name, r.regex);
        }
    }
    md
}

#[cfg(test)]
mod tests {
    #[test]
    fn committed_catalog_matches_the_code() {
        let committed =
            include_str!("../../../docs/docs/default-rules/catalog.md").replace("\r\n", "\n");
        let generated = super::markdown();
        assert!(
            committed == generated,
            "docs/docs/default-rules/catalog.md is out of date; regenerate with\n  \
             cargo run -p revoc-proxy -- list-rules > docs/docs/default-rules/catalog.md"
        );
    }

    #[test]
    fn every_pattern_has_a_governed_decision() {
        let md = super::markdown();
        assert!(md.contains("`pii_ssn_v1`"));
        assert!(md.contains("`secret_block_v1`"));
        assert!(md.contains("`mcp_result_pii_v1`"));
        assert!(md.contains("`session_data_exfil_v1`"));
    }
}
